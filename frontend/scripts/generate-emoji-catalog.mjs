// Builds src/emojiCatalog.ts, the emojis the reaction picker offers, from Unicode's
// emoji-test.txt (https://unicode.org/Public/emoji/<version>/emoji-test.txt):
//
//   node scripts/generate-emoji-catalog.mjs path/to/emoji-test.txt && npx prettier --write src/emojiCatalog.ts
//
// It keeps fully-qualified emojis without skin tones and leaves out the Component group.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const GROUPS = {
  'Smileys & Emotion': { name: 'Smileys', icon: '😀' },
  'People & Body': { name: 'People', icon: '👋' },
  'Animals & Nature': { name: 'Animals and nature', icon: '🐻' },
  'Food & Drink': { name: 'Food and drink', icon: '🍔' },
  'Travel & Places': { name: 'Travel and places', icon: '🚗' },
  Activities: { name: 'Activities', icon: '⚽' },
  Objects: { name: 'Objects', icon: '💡' },
  Symbols: { name: 'Symbols', icon: '🔣' },
  Flags: { name: 'Flags', icon: '🏁' },
};

const source = process.argv[2];
if (!source) throw new Error('Pass the path to emoji-test.txt');
const text = readFileSync(source, 'utf8');
const version = /^# Version: (\S+)/m.exec(text)?.[1] ?? 'unknown';
const groups = [];
let group = null;
for (const line of text.split(/\r?\n/)) {
  const heading = /^# group: (.+)$/.exec(line);
  if (heading) {
    const known = GROUPS[heading[1]];
    group = known ? { ...known, emojis: [] } : null;
    if (group) groups.push(group);
    continue;
  }
  const entry = /^[0-9A-F ]+; fully-qualified\s+# (\S+) E[\d.]+ (.+)$/.exec(line);
  if (!group || !entry || /skin tone/.test(entry[2])) continue;
  group.emojis.push([entry[1], entry[2]]);
}

const body = groups
  .map(
    (item) =>
      `  {\n    name: ${JSON.stringify(item.name)},\n    icon: ${JSON.stringify(item.icon)},\n    emojis: [\n${item.emojis
        .map(([emoji, name]) => `      [${JSON.stringify(emoji)}, ${JSON.stringify(name)}],`)
        .join('\n')}\n    ],\n  },`,
  )
  .join('\n');
const output = `// Generated by scripts/generate-emoji-catalog.mjs from Unicode emoji-test.txt ${version}.
// Do not edit by hand.

/** A picker category: its name, the emoji on its tab, and its emojis with their names. */
export interface EmojiGroup {
  name: string;
  icon: string;
  emojis: ReadonlyArray<readonly [emoji: string, name: string]>;
}

export const EMOJI_GROUPS: ReadonlyArray<EmojiGroup> = [
${body}
];
`;
const target = fileURLToPath(new URL('../src/emojiCatalog.ts', import.meta.url));
writeFileSync(target, output);
console.log(
  `Wrote ${groups.reduce((total, item) => total + item.emojis.length, 0)} emojis (${version}).`,
);
